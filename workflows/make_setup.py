"""Write scripts/runpod_setup.sh from MODELS (the one list of model files), so the setup script and the workflows
always agree on file names, folders and Hugging Face repos. Run: python workflows/make_setup.py"""
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
from build_workflows import MODELS  # noqa: E402

OUT = os.path.join(os.path.dirname(HERE), "scripts", "runpod_setup.sh")
GROUPS = {"ltx": ("ltx2_ckpt", "ltx2_depth_iclora", "ltx2_canny_iclora", "ltx2_distilled_lora", "ltx2_upscaler", "gemma3"),
          "flux1": ("flux1_dev", "flux1_depth_lora", "clip_l", "t5xxl", "flux_ae"),
          "flux2": ("flux2_dev", "mistral_flux2", "flux2_vae")}


def hf_parts(url):
    """https://huggingface.co/<org>/<repo>/resolve/main/<path> -> (org/repo, path)."""
    m = re.match(r"https://huggingface\.co/([^/]+/[^/]+)/resolve/main/(.+)$", url)
    if not m:
        raise ValueError(f"not a Hugging Face file URL: {url}")
    return m.group(1), m.group(2)


def model_lines(group):
    out = []
    for key in GROUPS[group]:
        name, folder, url, _ = MODELS[key]
        repo, path = hf_parts(url)
        assert os.path.basename(path) == name, (key, path, name)
        out.append(f"  get {repo} {path} {folder}")
    return "\n".join(out)


SCRIPT = r'''#!/usr/bin/env bash
# TitleRig on Runpod: ComfyUI + TitleRig + ComfyUI-LTXVideo + every model the AI workflows load.
# Generated by workflows/make_setup.py from MODELS in workflows/build_workflows.py. Do not edit by hand.
#
#   bash runpod_setup.sh            # everything (LTX-2 hero + FLUX.1 Depth + FLUX.2 dev), about 150 GB
#   bash runpod_setup.sh ltx        # only the LTX-2 hero
#   bash runpod_setup.sh ltx flux1  # LTX-2 + the FLUX.1 Depth still
#
# Re-runnable: clones and files already in place are skipped. Gated repos need a Hugging Face token with the licence
# accepted on the model page: export HF_TOKEN=hf_... before running.
set -uo pipefail
GROUPS_WANTED="${*:-ltx flux1 flux2}"
ROOT="${COMFY_ROOT:-/workspace}"
PY="${PYTHON:-python}"
FAILED=()

cd "$ROOT"
[ -d ComfyUI ] || git clone --depth 1 https://github.com/comfyanonymous/ComfyUI
cd ComfyUI
$PY -m pip install -q --upgrade pip
$PY -m pip install -q -r requirements.txt
$PY -m pip install -q "huggingface_hub[cli]" hf_transfer

[ -d custom_nodes/comfyui-titlerig ] || git clone --depth 1 https://github.com/Cozy-Art/comfyui-titlerig custom_nodes/comfyui-titlerig
$PY -m pip install -q -r custom_nodes/comfyui-titlerig/requirements.txt
# ComfyUI-LTXVideo is optional (TitleRig's LTX workflows use ComfyUI's built-in LTX-2 nodes); handy for its extras.
[ -d custom_nodes/ComfyUI-LTXVideo ] || git clone --depth 1 https://github.com/Lightricks/ComfyUI-LTXVideo custom_nodes/ComfyUI-LTXVideo
$PY -m pip install -q -r custom_nodes/ComfyUI-LTXVideo/requirements.txt || FAILED+=("ComfyUI-LTXVideo requirements (optional)")
cp custom_nodes/comfyui-titlerig/examples/assets/titlerig_beat.wav input/

export HF_HUB_ENABLE_HF_TRANSFER=1
if command -v huggingface-cli >/dev/null; then HFCLI=(huggingface-cli download); else HFCLI=(hf download); fi
TMP="$ROOT/hf_download"

get() {  # get <repo> <path in repo> <ComfyUI models folder>
  local dest="models/$3/$(basename "$2")"
  if [ -s "$dest" ]; then echo "have  $dest"; return; fi
  echo "fetch $dest"
  mkdir -p "models/$3"
  if "${HFCLI[@]}" "$1" "$2" --local-dir "$TMP" && mv "$TMP/$2" "$dest"; then return; fi
  FAILED+=("$dest  <- https://huggingface.co/$1 (licence accepted? HF_TOKEN set?)")
}

for group in $GROUPS_WANTED; do case "$group" in
ltx)
@LTX@
  ;;
flux1)
@FLUX1@
  ;;
flux2)
@FLUX2@
  ;;
*) echo "unknown group: $group (use ltx, flux1, flux2)"; exit 2 ;;
esac; done
rm -rf "$TMP"

$PY -c "import torch; print('torch', torch.__version__, '| CUDA', torch.cuda.is_available(), '|', torch.cuda.get_device_name(0) if torch.cuda.is_available() else 'no GPU')" \
  || echo "WARNING: torch does not import; pick a Runpod PyTorch template (CUDA 12.x)"
if [ ${#FAILED[@]} -gt 0 ]; then printf '\nNOT DONE:\n'; printf '  %s\n' "${FAILED[@]}"; fi
echo
echo "Start ComfyUI:  cd $ROOT/ComfyUI && $PY main.py --listen 0.0.0.0 --port 8188"
echo "Then open the pod's port 8188 and use Templates -> Extensions -> comfyui-titlerig."
'''

if __name__ == "__main__":
    text = SCRIPT.replace("@LTX@", model_lines("ltx")).replace("@FLUX1@", model_lines("flux1")) \
                 .replace("@FLUX2@", model_lines("flux2"))
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w") as f:
        f.write(text)
    os.chmod(OUT, 0o755)
    print("wrote", os.path.relpath(OUT, os.path.dirname(HERE)))
